  // Storage Persistence
  saveStateToStorage() {
    try {
      localStorage.setItem('aarogyam_state', JSON.stringify({
        profile: this.state.profile,
        water: {
          currentGlasses: this.state.water.currentGlasses,
          alarmEnabled: this.state.water.alarmEnabled,
          intervalMinutes: this.state.water.intervalMinutes
        },
        subscription: this.state.subscription,
        checklist: this.state.checklist
      }));
    } catch (e) {
      console.warn('Storage error:', e);
    }
  },

  loadStateFromStorage() {
    try {
      const data = localStorage.getItem('aarogyam_state');
      if (data) {
        const parsed = JSON.parse(data);
        if (parsed.profile) this.state.profile = Object.assign(this.state.profile, parsed.profile);
        if (parsed.water) this.state.water = Object.assign(this.state.water, parsed.water);
        if (parsed.subscription) this.state.subscription = Object.assign(this.state.subscription, parsed.subscription);
        if (parsed.checklist) this.state.checklist = Object.assign(this.state.checklist, parsed.checklist);

        // Update form fields to match saved profile
        const ageEl = document.getElementById('userAge');
        const weightEl = document.getElementById('userWeight');
        const heightEl = document.getElementById('userHeight');
        if (ageEl) ageEl.value = this.state.profile.age;
        if (weightEl) weightEl.value = this.state.profile.weight;
        if (heightEl) heightEl.value = this.state.profile.height;

        // Checkboxes
        document.querySelectorAll('.condition-checkbox').forEach(cb => {
          cb.checked = this.state.profile.conditions.includes(cb.value);
        });

        // Water alarm toggle
        const toggleEl = document.getElementById('waterAlarmToggle');
        if (toggleEl) toggleEl.checked = this.state.water.alarmEnabled;

        const intervalSelect = document.getElementById('reminderInterval');
        if (intervalSelect) intervalSelect.value = this.state.water.intervalMinutes;
      }
    } catch (e) {
      console.warn('Failed to load state from localStorage:', e);
    }
  }
